  /* ---------- hero: word reveal + scroll shift ---------- */
  function initHero() {
    var h1 = doc.querySelector('.h1');
    if (!h1 || reduce || !root.classList.contains('kinetic')) return;
    var words = [].slice.call(h1.querySelectorAll('.w > span'));
    var anims = words.map(function (w, i) {
      var a = w.animate([{ transform: 'translateY(105%)' }, { transform: 'translateY(0)' }], { duration: 820, delay: 80 + i * 75, easing: 'cubic-bezier(.2,0,0,1)', fill: 'forwards' });
      return a;
    });
    Promise.all(anims.map(function (a) { return a.finished; })).then(function () { root.classList.remove('kinetic'); anims.forEach(function (a) { a.cancel(); }); }).catch(function () {});
    function skip() { anims.forEach(function (a) { try { a.finish(); } catch (e) {} }); off(); }
    function off() { window.removeEventListener('keydown', skip); window.removeEventListener('pointerdown', skip); }
    window.addEventListener('keydown', skip);
    window.addEventListener('pointerdown', skip);

    var lines = [].slice.call(h1.querySelectorAll('.h1__line')), dir = [-1, 0.7, -0.4];
    var top0 = h1.getBoundingClientRect().top + window.scrollY, raf = 0;
    function tick() {
      raf = 0;
      var p = Math.max(0, Math.min(1, window.scrollY / 520));
      lines.forEach(function (l, i) { l.style.transform = 'translate3d(' + (dir[i] * p * 56).toFixed(1) + 'px,0,0)'; });
    }
    window.addEventListener('scroll', function () { if (!raf) raf = requestAnimationFrame(tick); }, { passive: true });
  }

  /* ---------- parallax ---------- */
  function initParallax() {
    if (reduce) return;
    var els = [].slice.call(doc.querySelectorAll('[data-parallax]')), raf = 0, SCALE = 1.18;
    function tick() {
      raf = 0;
      var vh = window.innerHeight;
      els.forEach(function (el) {
        var host = el.parentElement, r = host.getBoundingClientRect();
        if (r.bottom < -50 || r.top > vh + 50) return;
        var speed = parseFloat(el.dataset.parallax) || 0;
        var room = host.offsetHeight * (SCALE - 1) / 2 - 1;
        var y = Math.max(-room, Math.min(room, (r.top + r.height / 2 - vh / 2) * -speed));
        el.style.transform = 'translate3d(0,' + y.toFixed(1) + 'px,0) scale(' + SCALE + ')';
      });
    }
    function on() { if (!raf) raf = requestAnimationFrame(tick); }
    window.addEventListener('scroll', on, { passive: true });
    window.addEventListener('resize', on);
    on();
  }

  /* ---------- cases carousel ---------- */
  var track = doc.querySelector('.carousel__track');
  var slides = track ? [].slice.call(track.querySelectorAll('.case')) : [];
  var caseIdx = 0;
  var btnPrev = doc.querySelector('[data-case="prev"]'), btnNext = doc.querySelector('[data-case="next"]');
  var counter = doc.querySelector('.carousel__count'), dots = [].slice.call(doc.querySelectorAll('.dots button'));
  function pad(n) { return String(n).padStart(2, '0'); }
  function updateCases() {
    if (!track) return;
    counter.textContent = pad(caseIdx + 1) + ' / ' + pad(slides.length);
    btnPrev.disabled = caseIdx === 0;
    btnNext.disabled = caseIdx === slides.length - 1;
    dots.forEach(function (d, i) { d.setAttribute('aria-current', String(i === caseIdx)); d.setAttribute('aria-label', t('goto') + (i + 1)); });
    slides.forEach(function (s, i) { s.setAttribute('aria-label', 'Case ' + (i + 1) + t('ofWord') + slides.length); });
  }
  function goCase(i) {
    caseIdx = Math.max(0, Math.min(slides.length - 1, i));
    track.scrollTo({ left: slides[caseIdx].offsetLeft - track.offsetLeft, behavior: reduce ? 'auto' : 'smooth' });
    updateCases();
  }
  if (track) {
    btnPrev.addEventListener('click', function () { goCase(caseIdx - 1); });
    btnNext.addEventListener('click', function () { goCase(caseIdx + 1); });
    dots.forEach(function (d) { d.addEventListener('click', function () { goCase(+d.dataset.go); }); });
    track.addEventListener('keydown', function (e) {
      if (e.key === 'ArrowRight') { e.preventDefault(); goCase(caseIdx + 1); }
      if (e.key === 'ArrowLeft') { e.preventDefault(); goCase(caseIdx - 1); }
    });
    var st = 0;
    track.addEventListener('scroll', function () {
      clearTimeout(st);
      st = setTimeout(function () {
        var best = 0, dist = Infinity, x = track.scrollLeft;
        slides.forEach(function (s, i) { var d = Math.abs(s.offsetLeft - track.offsetLeft - x); if (d < dist) { dist = d; best = i; } });
        if (x + track.clientWidth >= track.scrollWidth - 4) best = slides.length - 1;
        if (best !== caseIdx) { caseIdx = best; updateCases(); }
      }, 80);
    }, { passive: true });
  }

